// Inlines the grade 1 content banks (stories, elkonin, chains, heartWords) from
// src/content/edu_content.js into apps/dino-star-patrol.html between the
// /*EDU1-BEGIN*/ ... /*EDU1-END*/ markers. The app must stay one self-contained file.
// Usage: node src/tools/inline-edu-dino.mjs
import {createRequire} from 'module';
import fs from 'fs';
import path from 'path';
import {fileURLToPath} from 'url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const require = createRequire(import.meta.url);
const EDU = require(path.join(root, 'src/content/edu_content.js'));
const pickKeys = (o, ks) => Object.fromEntries(Object.entries(o).filter(([k]) => ks.includes(k)));
const data = {
  stories: EDU.stories.map(s => pickKeys(s, ['id', 'pattern', 'title', 'heart', 'hf', 'text'])),
  elkonin: EDU.elkonin.map(e => pickKeys(e, ['w', 'gr'])),
  chains: EDU.chains,
  heartWords: EDU.heartWords.map(h => pickKeys(h, ['w', 'heart', 'why', 'flash'])),
};
const file = path.join(root, 'apps/dino-star-patrol.html');
const html = fs.readFileSync(file, 'utf8');
const re = /\/\*EDU1-BEGIN\*\/[\s\S]*?\/\*EDU1-END\*\//;
if (!re.test(html)) { console.error('markers not found'); process.exit(1); }
const block = `/*EDU1-BEGIN*/\n/* generated by src/tools/inline-edu-dino.mjs from src/content/edu_content.js (EDU v${EDU.version}); do not edit by hand */\nconst EDU1=${JSON.stringify(data)};\n/*EDU1-END*/`;
fs.writeFileSync(file, html.replace(re, () => block));
console.log('inlined EDU1:', data.stories.length, 'stories,', data.elkonin.length, 'elkonin,', data.chains.length, 'chains,', data.heartWords.length, 'heart words');
